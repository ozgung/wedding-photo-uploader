"""Generate A6/A4 QR cards from EVENT_* settings and locale copy. Default is a clearly labeled, non-live proof."""
import argparse
import json
import sys
from datetime import date
import math
import random
from pathlib import Path
from urllib.parse import urlsplit

import qrcode
from fontTools.ttLib import TTFont as Font
from fontTools.varLib.instancer import instantiateVariableFont
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.pdfgen.canvas import Canvas
from reportlab.lib.colors import HexColor
from reportlab.lib.units import mm

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from app.settings import LOCALES, Settings  # noqa: E402
NAVY, OLIVE = '#123454', '#879269'

def fonts():
    out = ROOT / 'tmp/print-fonts'
    out.mkdir(parents=True, exist_ok=True)
    for name, filename, axes in [('Sans', 'dm-sans', {'wght': 300, 'opsz': 14}), ('Serif', 'cormorant', {'wght': 400})]:
        font = Font(ROOT / f'app/static/fonts/{filename}.ttf')
        instantiateVariableFont(font, axes, inplace=True).save(out / f'{name}.ttf')
        pdfmetrics.registerFont(TTFont(name, out / f'{name}.ttf'))

def make_card(path, qr, scale, proof, title, when, main, second=None):
    w, h = 105*mm, 148*mm
    c = Canvas(str(path), pagesize=(w*scale, 297*mm if scale == 2 else h))
    c.setTitle(title + ' - QR card' + (' - DESIGN PROOF' if proof else ''))
    c.scale(scale, scale)
    def line(text, y, size=9, color=NAVY, font='Sans'):
        c.setFillColor(HexColor(color)); c.setFont(font, size)
        c.drawCentredString(w/2, y, text)
    def heart(x, y, s=1):
        c.saveState(); c.translate(x,y); c.scale(s,s)
        c.setStrokeColor(HexColor(OLIVE)); c.setLineWidth(.9)
        p=c.beginPath(); p.moveTo(0,-7); p.curveTo(-2,-1,-10,-1,-10,6); p.curveTo(-10,13,-3,13,0,7); p.curveTo(3,13,10,13,10,6); p.curveTo(10,-1,2,-1,0,-7); c.drawPath(p); c.restoreState()
    random.seed(12)
    for i in range(12):
        x=12+i*8; y=h-8-random.randrange(8,50)
        c.setStrokeColor(HexColor('#92997b'));c.setLineWidth(.4)
        p=c.beginPath();p.moveTo(-2,h+2);p.curveTo(x*.2,h-10,x*.1,y,x,y);c.drawPath(p)
        for j in range(3):
            ex=x*(.5+j*.2)+random.randrange(-3,10);ey=h-(h-y)*(.5+j*.2)
            c.setFillColor(HexColor('#faf8ed'));c.setStrokeColor(HexColor('#e5dfcb'));c.setLineWidth(.15)
            for a in range(5): c.circle(ex+math.cos(a*math.tau/5)*1.4,ey+math.sin(a*math.tau/5)*1.4,1.8,stroke=1,fill=1)
            c.setFillColor(HexColor('#b5a171'));c.circle(ex,ey,.4,stroke=0,fill=1)
    heart(w/2,365,.75)
    spaced=lambda text:' '.join(text.upper())
    if '&' in title:
        left,right=(part.strip() for part in title.split('&',1))
        line(spaced(left)+'       '+spaced(right),326,20)
        c.setFont('Serif',35);c.setFillColor(HexColor(OLIVE))
        c.drawCentredString(w/2+(pdfmetrics.stringWidth(spaced(left),'Sans',20)-pdfmetrics.stringWidth(spaced(right),'Sans',20))/2,324,'&')
    else:line(spaced(title),326,20)
    line('  ·  '.join(spaced(x) for x in (f'{when.day:02}',f'{when.month:02}',str(when.year))),305,8,OLIVE)
    line(main['invite'],277,14)
    line(main['card_share'],255,8.5)
    if second:line(second['card_share'],241,7.5,'#6e775e')
    matrix=qr.get_matrix(); n=len(matrix); size=48*mm; unit=size/n
    c.setFillColor(HexColor(NAVY)); ox=(w-size)/2;oy=91
    for y,row in enumerate(matrix):
        for x,on in enumerate(row):
            if on:c.rect(ox+x*unit,oy+(n-y-1)*unit,unit,unit,stroke=0,fill=1)
    line(main['card_scan'],78,9)
    if second:line(second['card_scan'],65,7.5,'#6e775e')
    line(' · '.join(x['card_no_app'] for x in (main,second) if x),47,6.3,'#6e775e')
    line(' · '.join(x['card_signoff'] for x in (main,second) if x),29,13,OLIVE,'Serif')
    if proof:line('DESIGN PROOF - QR is not a live invitation',12,6,'#9f3948')
    c.showPage();c.save()

def main():
    s=Settings()
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--invite-file',type=Path)
    p.add_argument('--lang',default=s.default_lang,help='Main card language (default: DEFAULT_LANG)')
    p.add_argument('--second-lang',help='Optional smaller second language, e.g. en')
    args=p.parse_args()
    copy=lambda code:json.loads((LOCALES/f'{code}.json').read_text()) if code else None
    main_copy,second_copy=copy(args.lang),copy(args.second_lang)
    proof=args.invite_file is None
    url=s.origin+'/#preview-not-an-invitation' if proof else args.invite_file.read_text().strip()
    if not proof and (urlsplit(url).scheme!='https' or not urlsplit(url).fragment.startswith('invite=')):
        p.error('Expected the HTTPS invitation URL generated by the owner setup command.')
    out=ROOT/('output/pdf' if proof else 'output/private');out.mkdir(parents=True,exist_ok=True)
    qr=qrcode.QRCode(error_correction=qrcode.constants.ERROR_CORRECT_Q,border=4,box_size=10);qr.add_data(url);qr.make(fit=True)
    fonts()
    for name,scale in [('a6-table-card',1),('a4-entrance-sign',2)]:
        path=out/(name+('-proof' if proof else '')+'.pdf');make_card(path,qr,scale,proof,s.event_title,date.fromisoformat(s.event_date),main_copy,second_copy)
        if not proof:path.chmod(0o600)
        print(path)

if __name__=='__main__':main()
